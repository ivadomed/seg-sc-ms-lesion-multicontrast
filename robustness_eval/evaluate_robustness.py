"""
This script evaluates the performance of a model and its robustness to small image changes, using the images generated by
generate_augmented_images.py (a copy and 4 augmented versions of each image).

Performance: Dice score, lesion-wise PPV, sensitivity and F1-score of each prediction against the mask of the same version
(for the affine version, the transformed mask), and predicted lesion volume (mm³), averaged per version.
Robustness: absolute change of each metric between an augmented version and the copy of the same image, averaged per
augmentation and globally (all augmentations pooled). The lower, the more robust. The predicted lesion volume variability
is given in mm³ (volume) and relative to the mean volume of both predictions (volume_%: 0% if both are empty, 200% if only one is).
Note: in the affine version, the in-plane scaling also changes the true lesion volume (by up to ~10%).

Input:
    --data-folder: Output folder of generate_augmented_images.py (containing the labels_<version>/ folders)
    --pred-folder: Folder containing the predictions, with the same structure as the images (images_copy/, images_affine/, ...)
    --output-folder: Folder to save the metrics per image (metrics.csv), the performance (performance.csv) and the robustness (robustness.csv)

Example:
    python evaluate_robustness.py --data-folder /path/to/augmented_data --pred-folder /path/to/predictions --output-folder /path/to/results

Author: Pierre-Louis Benveniste
"""
import argparse
import sys
from pathlib import Path
import nibabel as nib
import numpy as np
import pandas as pd
from tqdm import tqdm
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "evaluation"))
from utils import dice_score, lesion_ppv, lesion_f1_score, lesion_sensitivity

METRICS = ["dice", "ppv", "sensitivity", "f1", "volume"]


def parse_args():
    parser = argparse.ArgumentParser(description="Evaluate the performance and the robustness of a model on the augmented images.")
    parser.add_argument("--data-folder", required=True, help="Output folder of generate_augmented_images.py")
    parser.add_argument("--pred-folder", required=True, help="Folder containing the predictions (one folder per version)")
    parser.add_argument("--output-folder", required=True, help="Folder to save the results")
    return parser.parse_args()


def main():
    args = parse_args()
    output_folder = Path(args.output_folder)
    output_folder.mkdir(parents=True, exist_ok=True)

    # Metrics of each prediction against the mask of the same version, and predicted lesion volume (mm³)
    rows = []
    for pred_path in tqdm(sorted(Path(args.pred_folder).rglob("*.nii.gz"))):
        version = pred_path.parent.name.split("_")[-1]
        case = pred_path.name.replace("_0000.nii.gz", ".nii.gz")
        pred_image = nib.load(pred_path)
        pred = pred_image.get_fdata()
        label = nib.load(Path(args.data_folder) / f"labels_{version}" / case).get_fdata()
        rows.append({"case": case, "version": version, "dice": dice_score(pred, label), "ppv": lesion_ppv(label, pred),
                     "sensitivity": lesion_sensitivity(label, pred), "f1": lesion_f1_score(label, pred),
                     "volume": pred.sum() * np.prod(pred_image.header.get_zooms()[:3])})
    metrics = pd.DataFrame(rows)
    metrics.to_csv(output_folder / "metrics.csv", index=False)

    # Performance per version
    performance = metrics.groupby("version")[METRICS].agg(["mean", "std"])
    performance.to_csv(output_folder / "performance.csv")

    # Robustness: absolute change of each metric compared to the copy of the same image, per augmentation and globally
    changes = metrics[metrics.version != "copy"].merge(metrics[metrics.version == "copy"], on="case", suffixes=("", "_copy"))
    changes["volume_%"] = (200 * (changes.volume - changes.volume_copy).abs() / (changes.volume + changes.volume_copy)).fillna(0)
    changes[METRICS] = (changes[METRICS] - changes[[f"{metric}_copy" for metric in METRICS]].values).abs()
    robustness = pd.concat([changes, changes.assign(version="global")]).groupby("version")[METRICS + ["volume_%"]].agg(["mean", "std"])
    robustness.to_csv(output_folder / "robustness.csv")

    print(f"Performance (volume in mm³):\n{performance.round(3)}\n\nRobustness (absolute change compared to the copy, the lower the better):\n{robustness.round(3)}")


if __name__ == "__main__":
    main()
